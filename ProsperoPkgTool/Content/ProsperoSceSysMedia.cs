using ProsperoPkgTool.Containers;

namespace ProsperoPkgTool.Content;

/// <summary>
/// Clean-room mapping from <c>sce_sys</c> media/system files to their outer CNT entries, mirroring
/// how a publisher package splits a prepared application tree: recognised <c>sce_sys</c> files
/// become CNT entries (never inner-PFS files), and the PNG icons/pictures additionally get a
/// generated BC7 <c>*.dds</c> companion when the DDS is not supplied.
/// </summary>
public static class ProsperoSceSysMedia
{
    /// <summary>One collected outer-CNT media/system entry.</summary>
    public sealed record Entry(CntEntryId Id, string? Name, byte[] Data, uint Flags1, uint Flags2);

    // sce_sys files copied verbatim as media (id 0x1001 is generated by the PlayGo builder instead).
    private static readonly (string Name, CntEntryId Id)[] MediaFiles =
    [
        ("icon0.png", CntEntryId.Icon0Png),
        ("pic0.png", CntEntryId.Pic0Png),
        ("pic1.png", CntEntryId.Pic1Png),
        ("pic2.png", CntEntryId.Pic2Png),
        ("snd0.at9", CntEntryId.Snd0At9),
        ("save_data.png", CntEntryId.SaveDataPng),
    ];

    // PNG sources that get a BC7 DDS companion (the reference DDS id differs from the PNG id).
    private static readonly (string Png, string Dds, CntEntryId Id)[] DdsMedia =
    [
        ("icon0.png", "icon0.dds", CntEntryId.Icon0Dds),
        ("pic0.png", "pic0.dds", CntEntryId.Pic0Dds),
        ("pic1.png", "pic1.dds", CntEntryId.Pic1Dds),
        ("pic2.png", "pic2.dds", CntEntryId.Pic2Dds),
    ];

    private static readonly IReadOnlyDictionary<string, CntEntryId> NameToId = BuildNameMap();

    /// <summary>The CNT entry id for a sce_sys-relative path, when it is a recognised outer entry.</summary>
    public static bool TryGetId(string sceSysRelativePath, out CntEntryId id) =>
        NameToId.TryGetValue(sceSysRelativePath, out id);

    /// <summary>
    /// True when a <c>sce_sys/&lt;relative&gt;</c> file is an outer CNT entry (param.json, pic2.png,
    /// or any recognised system/media name) and therefore must not enter the inner PFS.
    /// </summary>
    public static bool IsOuterCntFile(string sceSysRelativePath) =>
        sceSysRelativePath == "param.json" ||
        sceSysRelativePath == "pic2.png" ||
        NameToId.ContainsKey(sceSysRelativePath);

    /// <summary>
    /// Collects the outer-CNT media/system entries for the supplied <c>sce_sys</c> files. The key is
    /// the path relative to <c>sce_sys</c> with forward slashes. Media PNGs are emitted verbatim and
    /// their DDS companions are generated with the clean-room BC7 encoder; an unreadable PNG simply
    /// skips its DDS (the PNG entry is still emitted), matching the reference's best-effort rule.
    /// </summary>
    public static IReadOnlyList<Entry> Collect(
        IReadOnlyDictionary<string, byte[]> sceSysFiles,
        string? applicationDrmType = null,
        bool generateDds = true)
    {
        ArgumentNullException.ThrowIfNull(sceSysFiles);
        var result = new List<Entry>();
        var emitted = new HashSet<uint>();

        void Add(CntEntryId id, string? name, byte[] data)
        {
            ProsperoCntEntryProfile profile = ProsperoCntEntryPolicy.Resolve((uint)id, name, applicationDrmType);
            result.Add(new Entry(id, profile.IncludeName ? name : null, data, profile.Flags1, profile.Flags2));
        }

        foreach ((string name, CntEntryId id) in MediaFiles)
        {
            if (sceSysFiles.TryGetValue(name, out byte[]? data) && emitted.Add((uint)id))
                Add(id, name, data);
        }

        if (generateDds)
        {
            foreach ((string png, string dds, CntEntryId id) in DdsMedia)
            {
                if (!emitted.Add((uint)id))
                    continue;
                if (sceSysFiles.TryGetValue(dds, out byte[]? supplied))
                {
                    Add(id, dds, supplied);
                    continue;
                }
                if (!sceSysFiles.TryGetValue(png, out byte[]? pngData))
                    continue;
                try
                {
                    Add(id, dds, ProsperoDdsEncoder.EncodePngToDds(pngData));
                }
                catch (Exception ex) when (ex is InvalidDataException or NotSupportedException or ArgumentException)
                {
                    Console.Error.WriteLine($"  warning: skipped {dds} (could not encode {png}: {ex.Message})");
                }
            }
        }

        foreach (string name in sceSysFiles.Keys.OrderBy(k => k, StringComparer.OrdinalIgnoreCase))
        {
            if (name.EndsWith(".dds", StringComparison.Ordinal) ||
                name == "param.sfo" ||
                !NameToId.TryGetValue(name, out CntEntryId id) ||
                !emitted.Add((uint)id))
                continue;
            Add(id, name, sceSysFiles[name]);
        }

        return result;
    }

    private static IReadOnlyDictionary<string, CntEntryId> BuildNameMap()
    {
        var map = new Dictionary<string, CntEntryId>(StringComparer.Ordinal)
        {
            [".digests"] = CntEntryId.Digests,
            [".entry_keys"] = CntEntryId.EntryKeys,
            [".image_key"] = CntEntryId.ImageKey,
            [".general_digests"] = CntEntryId.GeneralDigests,
            [".metas"] = CntEntryId.Metas,
            [".entry_names"] = CntEntryId.EntryNames,
            ["license.dat"] = CntEntryId.LicenseDat,
            ["license.info"] = CntEntryId.LicenseInfo,
            ["nptitle.dat"] = CntEntryId.NptitleDat,
            ["npbind.dat"] = CntEntryId.NpbindDat,
            ["selfinfo.dat"] = CntEntryId.SelfinfoDat,
            ["imageinfo.dat"] = CntEntryId.ImageinfoDat,
            ["target-deltainfo.dat"] = CntEntryId.TargetDeltainfoDat,
            ["origin-deltainfo.dat"] = CntEntryId.OriginDeltainfoDat,
            ["psreserved.dat"] = CntEntryId.PsreservedDat,
            ["param.sfo"] = CntEntryId.ParamSfo,
            ["playgo-chunk.dat"] = CntEntryId.PlaygoChunkDat,
            ["playgo-chunk.sha"] = CntEntryId.PlaygoChunkSha,
            ["playgo-manifest.xml"] = CntEntryId.PlaygoManifestXml,
            ["pronunciation.sig"] = CntEntryId.PronunciationSig,
            ["pronunciation.xml"] = CntEntryId.PronunciationXml,
            ["pic1.png"] = CntEntryId.Pic1Png,
            ["pubtoolinfo.dat"] = CntEntryId.PubtoolinfoDat,
            ["app/playgo-chunk.dat"] = CntEntryId.AppPlaygoChunkDat,
            ["app/playgo-chunk.sha"] = CntEntryId.AppPlaygoChunkSha,
            ["app/playgo-manifest.xml"] = CntEntryId.AppPlaygoManifestXml,
            ["shareparam.json"] = CntEntryId.ShareparamJson,
            ["shareoverlayimage.png"] = CntEntryId.ShareoverlayimagePng,
            ["save_data.png"] = CntEntryId.SaveDataPng,
            ["shareprivacyguardimage.png"] = CntEntryId.ShareprivacyguardimagePng,
            ["icon0.png"] = CntEntryId.Icon0Png,
            ["pic0.png"] = CntEntryId.Pic0Png,
            ["snd0.at9"] = CntEntryId.Snd0At9,
            ["changeinfo/changeinfo.xml"] = CntEntryId.ChangeinfoXml,
            ["icon0.dds"] = CntEntryId.Icon0Dds,
            ["pic0.dds"] = CntEntryId.Pic0Dds,
            ["pic1.dds"] = CntEntryId.Pic1Dds,
            ["trophy2/trophy00.ucp"] = CntEntryId.Trophy2Ucp,
            ["uds/uds00.ucp"] = CntEntryId.UdsUcp,
            ["uds/npbind.dat"] = CntEntryId.UdsNpbind,
            ["trophy2/npbind.dat"] = CntEntryId.Trophy2Npbind,
            ["pic2.png"] = CntEntryId.Pic2Png,
            ["pic2.dds"] = CntEntryId.Pic2Dds,
        };

        for (int i = 0; i < 31; i++)
        {
            map[$"icon0_{i:d2}.png"] = (CntEntryId)(4609 + i);
            map[$"icon0_{i:d2}.dds"] = (CntEntryId)(4737 + i);
            map[$"pic1_{i:d2}.png"] = (CntEntryId)(4673 + i);
            map[$"pic1_{i:d2}.dds"] = (CntEntryId)(4801 + i);
            map[$"changeinfo/changeinfo_{i:d2}.xml"] = (CntEntryId)(4705 + i);
            if (i < 10)
                map[$"keymap_rp/{i + 1:d2}.png"] = (CntEntryId)(5632 + i);
            for (int j = 0; j < 10; j++)
                map[$"keymap_rp/{i:d2}/{j + 1:d2}.png"] = (CntEntryId)(5648 + 16 * i + j);
        }
        for (int k = 0; k < 100; k++)
            map[$"trophy/trophy{k:d2}.trp"] = (CntEntryId)(5120 + k);

        return map;
    }
}
